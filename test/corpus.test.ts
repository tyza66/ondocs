/** What `ondocs eval` of the sample eval file scores on the corpus, keyword-only. */
const SCORES = {
  'hit@1': '14/22',
  'hit@3': '19/22',
  'hit@5': '19/22',
  mrr: '0.73',
  refusalPrecision: '6/7',
  refusalRecall: '6/6',
};

/** `ondocs eval` of the sample eval file of the audit’s questions on `index`: each score, and the exit code. */
async function evalScores(index: AskIndexFile) {
  const dir = await mkdtemp(join(tmpdir(), 'ondocs-corpus-eval-'));
  try {
    await writeIndexFile(join(dir, 'ask-index.json'), index);
    const out: string[] = [];
    const code = await main(
      [
        'eval',
        join(import.meta.dirname, 'eval/docusaurus.io.yaml'),
        '--index',
        'ask-index.json',
        '--json',
      ],
      { cwd: dir, env: {}, stdout: (line) => out.push(line), stderr: () => undefined },
    );
    const { scores } = JSON.parse(out.join('\n')) as {
      scores: Record<string, { value: number; count: number; of: number }>;
    };
    return {
      code,
      scores: Object.fromEntries(
        Object.entries(scores).map(([name, { value, count, of }]) => [
          name,
          name === 'mrr' ? value.toFixed(2) : `${String(count)}/${String(of)}`,
        ]),
      ),
    };
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

const OFF_TOPIC = [
  'What is the capital of France?',
  'How do I bake sourdough bread?',
  'How do I configure a Kubernetes ingress controller?',
  'Who won the 2022 World Cup?',
  'Write me a poem about the sea',
  'kubernetes ingress',
  'sourdough recipe',
  'django orm migrations',
];

describe.skipIf(!present)(
  'search on docusaurus.io’s docs (keyword-only, as with no embedding model)',
  async () => {
    const documents = present
      ? await loadDirectory(docs, { baseUrl: '/docs', framework: 'docusaurus' })
      : [];
    const { index } = await buildIndex({ documents });
    const loaded = loadIndex(index);
    const mcp = createMcpHandler({
      index: loaded,
      siteUrl: 'https://docusaurus.io',
      rateLimit: false,
    });
    let id = 0;
    const call = async (name: string, args: Record<string, unknown>) => {
      const response = await mcp(
        new Request('https://docusaurus.io/api/mcp', {
          method: 'POST',
          headers: {
            'content-type': 'application/json',
            accept: 'application/json, text/event-stream',
          },
          body: JSON.stringify({
            jsonrpc: '2.0',
            id: (id += 1),
            method: 'tools/call',
            params: { name, arguments: args },
          }),
        }),
      );
      const body = (await response.json()) as {
        result: { structuredContent: Record<string, unknown>; isError?: boolean };
      };
      return body.result;
    };
    const rank = async (query: string, pages: string[]): Promise<number> => {
      const { results } = (await call('search', { query })).structuredContent as {
        results: { id: string }[];
      };
      const found = [...new Set(results.map((result) => result.id.split('#')[0] ?? ''))];
      return found.findIndex((page) => pages.includes(page));
    };

    it('indexes every page', () => {
      expect([documents.length, index.chunks.length]).toEqual([92, 1070]);
    });

    it('finds the page an agent is looking for in the top three, for every query', async () => {
      const ranks = await Promise.all(NEEDS.map(([, query, pages]) => rank(query, pages)));
      const top = (k: number) => ranks.filter((r) => r >= 0 && r < k).length;
      expect({
        top1: top(1),
        top3: top(3),
        misses: NEEDS.filter((_, i) => (ranks[i] ?? -1) < 0 || (ranks[i] ?? 0) >= 3).map(
          ([, q]) => q,
        ),
      }).toEqual({
        top1: 19,
        top3: 22,
        misses: [],
      });
    });

    it('finds the page for most questions asked as a person asks them', async () => {
      const ranks = await Promise.all(NEEDS.map(([question, , pages]) => rank(question, pages)));
      expect(ranks.filter((r) => r >= 0 && r < 3).length).toBe(20);
    });

    it('returns nothing for off-topic queries, with a note on what to try', async () => {
      const counts = await Promise.all(
        OFF_TOPIC.map(async (query) => {
          const { results, note } = (await call('search', { query })).structuredContent as {
            results: unknown[];
            note?: string;
          };
          return [results.length, note?.includes('list_pages')];
        }),
      );
      expect(counts).toEqual(OFF_TOPIC.map(() => [0, true]));
    });

    it('scores the sample eval file of the audit’s questions, as asked, within its thresholds', async () => {
      // A keyword-only index gates at 0.4 rather than 0.5: one question more is answered, from
      // the right page, and no off-topic one.
      expect(await evalScores(index)).toEqual({ code: 0, scores: SCORES });
    });

    it('fetches every page and every result, and lists them all', async () => {
      for (const document of documents) {
        const result = await call('fetch', { id: document.url });
        expect([document.url, result.isError ?? false]).toEqual([document.url, false]);
        expect((result.structuredContent.text as string).startsWith(`# ${document.title}`)).toBe(
          true,
        );
      }
      const { results } = (await call('search', { query: 'sidebar category index' }))
        .structuredContent as {
        results: { id: string; url: string }[];
      };
      for (const result of results) {
        const fetched = await call('fetch', { id: result.url });
        expect(fetched.structuredContent.url).toBe(result.url);
      }
      const list = await call('list_pages', {});
      expect(list.structuredContent.total).toBe(92);
    });
  },
);

// A versioned site serves its docs once per version: here the same docs at /docs, the last
// version, and at /docs/next, the unreleased one, as Docusaurus serves them. Every section has a
// copy, word for word, that scores the same on every query; retrieval counts the copies once, at
// the shorter URL, so the second version takes no place in the results and cites nothing at
// /docs/next.
describe.skipIf(!present)(
  'search on docusaurus.io’s docs in two versions, at /docs and /docs/next',
  async () => {
    const version = async (baseUrl: string) =>
      present
        ? (await loadDirectory(docs, { baseUrl, framework: 'docusaurus' })).map((document) => ({
            ...document,
            id: `${baseUrl}/${document.id}`,
          }))
        : [];
    const { index } = await buildIndex({
      documents: [...(await version('/docs')), ...(await version('/docs/next'))],
    });
    const loaded = loadIndex(index);

    it('indexes both versions', () => {
      expect([index.documents.length, index.chunks.length]).toEqual([184, 2140]);
    });

    it('finds what one version finds for an agent, and cites only the last version', () => {
      const results = NEEDS.map(([, query]) => searchSections(loaded, query, null, {}));
      const ranks = results.map((found, i) =>
        [...new Set(found.map((result) => result.id.split('#')[0] ?? ''))].findIndex((page) =>
          NEEDS[i]?.[2].includes(page),
        ),
      );
      expect({
        top1: ranks.filter((r) => r === 0).length,
        top3: ranks.filter((r) => r >= 0 && r < 3).length,
        next: results.flat().filter((result) => result.id.startsWith('/docs/next/')).length,
      }).toEqual({ top1: 19, top3: 22, next: 0 });
    });

    it('scores the sample eval file as one version does', async () => {
      expect(await evalScores(index)).toEqual({ code: 0, scores: SCORES });
    });
  },
);
